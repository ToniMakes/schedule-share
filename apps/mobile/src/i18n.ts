export type MessageKey = keyof typeof messages.en;

export function translate(
  language: AppLanguage,
  key: MessageKey,
  values: Readonly<Record<string, string | number>> = {}
): string {
  return messages[language][key].replace(/\{(\w+)\}/g, (_, name: string) =>
    String(values[name] ?? "")
  );
}
